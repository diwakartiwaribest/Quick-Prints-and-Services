let currentLang = localStorage.getItem('lang') || 'en';

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('lang', lang);
    
    // Update language toggle button text
    const langBtnText = document.getElementById('lang-btn-text');
    if (langBtnText) {
        langBtnText.textContent = lang === 'en' ? 'हिं' : 'EN';
    }

    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            if (element.tagName === 'P' || element.tagName === 'SPAN' || element.tagName === 'H1' || element.tagName === 'H2' || element.tagName === 'H3' || element.tagName === 'H4' || element.tagName === 'DIV' || element.tagName === 'A') {
                // If it contains icons, we need to preserve them. 
                // A simple way is to replace only text nodes or wrap text in spans.
                // We'll update innerHTML since about-text contains <strong>
                element.innerHTML = translations[lang][key];
            }
        }
    });
}

document.addEventListener('DOMContentLoaded', () => {
    
    // Initialize Language
    setLanguage(currentLang);
    const langToggle = document.getElementById('lang-toggle');
    if (langToggle) {
        langToggle.addEventListener('click', (e) => {
            e.preventDefault();
            const newLang = currentLang === 'en' ? 'hi' : 'en';
            setLanguage(newLang);
        });
    }

    // Set Current Year in Footer
    const yearSpan = document.getElementById('year');
    if (yearSpan) {
        yearSpan.textContent = new Date().getFullYear();
    }

    // Loader Remove
    window.addEventListener('load', () => {
        const loader = document.getElementById('loader');
        if (loader) {
            loader.style.opacity = '0';
            setTimeout(() => { loader.style.display = 'none'; }, 500);
        }
    });

    // Sticky Navbar (desktop only) & Back to Top Button
    const navbar   = document.getElementById('navbar');
    const backToTopBtn = document.getElementById('backToTop');

    window.addEventListener('scroll', () => {
        // Sticky navbar style on desktop
        if (navbar) {
            if (window.scrollY > 50) {
                navbar.classList.add('scrolled');
            } else {
                navbar.classList.remove('scrolled');
            }
        }
        // Back-to-top visibility
        if (window.scrollY > 400) {
            backToTopBtn.classList.add('show');
        } else {
            backToTopBtn.classList.remove('show');
        }
    });

    // Back to Top
    if (backToTopBtn) {
        backToTopBtn.addEventListener('click', () => {
            window.scrollTo({ top: 0, behavior: 'smooth' });
        });
    }

    // ---------------------------------------------------
    // Active link highlighting on scroll
    // Works for both desktop (.nav-link) and mobile (.mob-nav-link)
    // ---------------------------------------------------
    const sections      = document.querySelectorAll('section[id]');
    const desktopLinks  = document.querySelectorAll('.nav-link');
    const mobileLinks   = document.querySelectorAll('.mob-nav-link');

    function updateActiveLinks() {
        let current = '';
        sections.forEach(section => {
            const sectionTop = section.offsetTop - 120;
            if (window.scrollY >= sectionTop) {
                current = section.getAttribute('id');
            }
        });

        // Desktop
        desktopLinks.forEach(link => {
            link.classList.remove('active');
            const href = link.getAttribute('href');
            if (href && href.includes(current)) {
                link.classList.add('active');
            }
        });

        // Mobile bottom bar
        mobileLinks.forEach(link => {
            link.classList.remove('active');
            const href = link.getAttribute('href');
            if (href && href.includes(current)) {
                link.classList.add('active');
            }
        });
    }

    window.addEventListener('scroll', updateActiveLinks, { passive: true });
    updateActiveLinks(); // run once on load

    // Smooth-scroll for mobile bottom nav links + bounce animation
    mobileLinks.forEach(link => {
        link.addEventListener('click', (e) => {
            const href = link.getAttribute('href');
            if (href && href.startsWith('#')) {
                e.preventDefault();
                // Bounce the icon
                link.classList.add('bounce');
                link.addEventListener('animationend', () => link.classList.remove('bounce'), { once: true });
                const target = document.querySelector(href);
                if (target) {
                    target.scrollIntoView({ behavior: 'smooth' });
                }
            }
        });
    });

    // ---------------------------------------------------
    // Fade-in + pop-in Animation Observer
    // Targets: .fade-in-up, .service-card, .why-card, .title-underline
    // ---------------------------------------------------
    const observeTargets = document.querySelectorAll(
        '.fade-in-up, .service-card, .why-card, .title-underline'
    );
    const appearOptions = { threshold: 0.12, rootMargin: '0px 0px -40px 0px' };

    const appearOnScroll = new IntersectionObserver((entries, observer) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('visible');
                observer.unobserve(entry.target);
            }
        });
    }, appearOptions);

    observeTargets.forEach(el => appearOnScroll.observe(el));

});

